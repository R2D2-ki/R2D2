// Ersetzt {nombre} durch den Namen aus den Einstellungen (Standard: Melanie).
export function personalize(scenes, nombre) {
  const name = (nombre || '').replace(/[\\"{}]/g, '').trim() || 'Melanie';
  return JSON.parse(JSON.stringify(scenes).replaceAll('{nombre}', name));
}
